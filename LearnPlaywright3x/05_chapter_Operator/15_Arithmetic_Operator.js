//Arithmetic Operators
//let sum = a+b; // addition
//let subtraction = a-b; // subtraction
//let multiplication = a*b; // multiplication
//let division = a/b; // division 

let sum = 10 + 5; // addition
console.log(sum);

let difference = 10 - 5; // subtraction
console.log(difference);

let product = 10 * 5; // multiplication
console.log(product);

let quotient = 10 / 5; // division
console.log(quotient);

let remainder = 10 % 3; // modulus
console.log(remainder);

//Modulus operator returns the remainder of a division operation. For example, 10 % 3 equals 1 because when you divide 10 by 3, the quotient is 3 and the remainder is 1.
console.log(10 % 3); // Output: 1
console.log(15 % 4); // Output: 3
console.log(20 % 6); // Output: 2

//n%2 ==1 - odd number
//n%2 ==0 - even number

//Exponentiation operator (**)
let base = 2;
let exponent = 3;
let result = base ** exponent;
console.log(result); // Output: 8
console.log(2 ** 3); // Output: 8
console.log(5 ** 2); // Output: 25